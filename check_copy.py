def font_of(style):
    if style not in _cache:
        fam, wt, sz = STYLES[style]
        _cache[style] = ImageFont.truetype(FONT_PATH[(fam, wt)], sz)
    return _cache[style]

def font_at(family, weight, size):
    key = (family, weight, size)
    if key not in _cache:
        _cache[key] = ImageFont.truetype(FONT_PATH[(family, weight)], size)
    return _cache[key]

