def wrap_outlets(sources, font, width):
    units = ["Sources: " + sources[0]] + list(sources[1:])
    lines, cur = [], ""
    for u in units:
        t = u if not cur else cur + ", " + u
        if font.getlength(t) <= width or not cur:
            cur = t
        else:
            lines.append(cur); cur = u
    if cur:
        lines.append(cur)
    return lines
