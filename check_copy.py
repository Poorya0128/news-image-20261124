def wrap(text, font, width_px):
    words, lines, cur = text.split(" "), [], ""
    for w_ in words:
        t = (cur + " " + w_).strip()
        if font.getlength(t) <= width_px or not cur:
            cur = t
        else:
            lines.append(cur); cur = w_
    if cur:
        lines.append(cur)
    return lines

def check(name, text, style, width, max_lines=1, exact_lines=False):
    f = font_of(style)
    lines = wrap(text, f, width)
    ok = len(lines) <= max_lines and all(f.getlength(l) <= width for l in lines)
    if exact_lines:
        ok = ok and len(lines) == max_lines
    widest = max((f.getlength(l) for l in lines), default=0)
    print(f"{'OK ' if ok else 'FAIL'} {name}: {len(lines)} line(s), widest {widest:.0f}/{width}px {text!r}")
    if not ok:
        fails.append(f"{name}: {len(lines)} lines, widest {widest:.0f}/{width}px")
    return lines

def check_fixed(name, text, style, width):
    f = font_of(style)
    wpx = f.getlength(text)
    ok = wpx <= width
    print(f"{'OK ' if ok else 'FAIL'} {name} (fixed): {wpx:.0f}/{width}px {text!r}")
    if not ok:
        fails.append(f"{name}: {wpx:.0f}px > {width}px")

def check_lead_sources(name, c):
    """Leads (old format): sources = ' · '.join(sources), no status prefix (status in tag)."""
    full = " · ".join(c["sources"])
    assert c["source_line"] == full, f"{name}: source_line drift"
    w = font_of("source_line").getlength(full)
    ok = w <= 300 and c.get("source_lines") == [full]
    print(f"{'OK ' if ok else 'FAIL'} {name}.source_line: {w:.0f}/300px {full!r}")
    if not ok:
        fails.append(f"{name} source_line")

def check_feature_sources(name, c, inner, two_line=False):
    """Features: composed 'STATUS — A · B' (status Bold 10 + ' — ' + sources Regular 10)."""
    swf, slf = font_of("source_status"), font_of("source_line")
    full = c["status_word"] + " — " + " · ".join(c["sources"])
    assert c["source_line"] == full, f"{name}: source_line drift"
    w = swf.getlength(c["status_word"]) + slf.getlength(" — " + " · ".join(c["sources"]))
    if w <= inner:
        ok = c.get("source_lines") == [full]
        print(f"{'OK ' if ok else 'FAIL'} {name}.source_line: {w:.0f}/{inner}px {full!r}")
        if not ok:
            fails.append(f"{name} source_lines != [composed]")
        return
    if two_line:
        l1 = c["status_word"] + " — " + c["sources"][0] + " ·"
        l2 = c["sources"][1]
        w1 = swf.getlength(c["status_word"]) + slf.getlength(" — " + c["sources"][0] + " ·")
        w2 = slf.getlength(l2)
        ok = w1 <= inner and w2 <= inner and c.get("source_lines") == [l1, l2]
        print(f"{'OK ' if ok else 'FAIL'} {name}.source_line (2-line): {w1:.0f}+{w2:.0f}/{inner}px {l1!r} | {l2!r}")
        if not ok:
            fails.append(f"{name} source_line two-line wrap")
        return
    print(f"FAIL {name}.source_line: {w:.0f}/{inner}px {full!r}")
    fails.append(f"{name} source_line overflow")

def check_feature_chip(name, c, inner, expected_size, focal_waived=False, sizes=(13, 12, 11)):
    """Feature chip: largest of {13,12,11} with box-fit (6+text+14 <= scene+8)
    AND focal clearance (chip_right <= 0.75*scene). Exceptions per spec Sec 6.2/12."""
    chosen = None
    for sz in sizes:
        t = font_at("Liberation Sans", "Bold", sz).getlength(c["badge"])
        box_right = 6 + t + 14
        if box_right <= inner + 8 and (focal_waived or box_right <= 0.75 * inner):
            chosen = (sz, t, box_right)
            break
    ok = chosen is not None and chosen[0] == expected_size
    if chosen:
        print(f"{'OK ' if ok else 'FAIL'} {name}.badge chip @{chosen[0]}px: text {chosen[1]:.0f}px, box right {chosen[2]:.0f}/{inner}px ({100*chosen[2]/inner:.0f}%) {c['badge']!r}")
    else:
        print(f"FAIL {name}.badge chip: no size in {sizes} satisfies box-fit+focal {c['badge']!r}")
    if not ok:
        fails.append(f"{name} badge chip size")

